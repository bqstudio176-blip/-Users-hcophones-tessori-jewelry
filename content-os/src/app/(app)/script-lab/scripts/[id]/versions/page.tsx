import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { EmptyState, PageHeader } from "@/components/ui/states";
import { getWorkspaceContext } from "@/lib/auth/session";
import { formatDateTime } from "@/lib/format";
import { createClient } from "@/lib/supabase/server";
import { uuidSchema } from "@/lib/validation";
import { restoreScriptVersion } from "@/server/actions/creative";
import { labelOf, SCRIPT_SECTIONS } from "@/server/creative/catalog";

export const metadata: Metadata = { title: "Version history" };

const SOURCE_LABEL: Record<string, string> = {
  generated: "Generated by AI", manual_save: "Saved manually", before_ai_edit: "Before AI edit", ai_edit_applied: "AI edit applied (confirmed)",
  before_restore: "Before restore", restored: "Restored",
};

type Snapshot = { title?: string; scenes?: { section: string; scene_title: string; spoken_text: string; estimated_duration_seconds: number }[] };

export default async function VersionsPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ v?: string }> }) {
  await getWorkspaceContext();
  const { id } = await params;
  const { v } = await searchParams;
  if (!uuidSchema.safeParse(id).success) notFound();
  const supabase = await createClient();
  const { data: script } = await supabase.from("scripts").select("id, title, current_version").eq("id", id).maybeSingle();
  if (!script) notFound();
  const { data: versions } = await supabase.from("script_versions").select("id, version, source, note, snapshot, created_at").eq("script_id", id).order("version", { ascending: false });
  const list = versions ?? [];
  const selected = list.find((x) => String(x.version) === v) ?? list[0];
  const snap = (selected?.snapshot ?? {}) as Snapshot;

  return (
    <>
      <PageHeader title="Version history" description={<><Link href={`/script-lab/scripts/${id}`} className="text-accent">{script.title}</Link> · current version {script.current_version}</>} />
      {list.length === 0 ? (
        <EmptyState title="No versions yet" description="Versions are created when a script is generated, saved, edited by AI or restored." />
      ) : (
        <div className="grid gap-6 lg:grid-cols-[20rem_1fr]">
          <ol className="space-y-2">
            {list.map((x) => (
              <li key={x.id}>
                <Link href={`?v=${x.version}`} className={`block rounded-lg border p-3 text-sm transition-colors ${selected?.id === x.id ? "border-accent bg-surface-2" : "border-line hover:bg-surface-2"}`}>
                  <div className="flex items-center justify-between"><span className="font-medium text-fg">Version {x.version}</span><span className="text-xs text-fg-subtle">{formatDateTime(x.created_at)}</span></div>
                  <p className="mt-1 text-xs text-fg-muted">{SOURCE_LABEL[x.source] ?? x.source}{x.note ? ` — ${x.note}` : ""}</p>
                </Link>
              </li>
            ))}
          </ol>
          {selected && (
            <Card>
              <CardHeader>
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <CardTitle>Version {selected.version}: {snap.title ?? script.title}</CardTitle>
                  <form action={restoreScriptVersion}>
                    <input type="hidden" name="scriptId" value={id} />
                    <input type="hidden" name="version" value={selected.version} />
                    <Button type="submit" size="sm" variant="outline">Restore this version</Button>
                  </form>
                </div>
                <p className="text-xs text-fg-subtle">Restoring first saves the current content as a new version, so nothing is lost.</p>
              </CardHeader>
              <CardContent>
                <ol className="space-y-3">
                  {(snap.scenes ?? []).map((s, i) => (
                    <li key={i} className="rounded-md border border-line p-3 text-sm">
                      <div className="mb-1 flex items-center gap-2"><span className="text-xs text-fg-subtle">{i + 1}.</span><span className="font-medium text-fg">{s.scene_title}</span><Badge>{labelOf(SCRIPT_SECTIONS, s.section)}</Badge><Badge>{s.estimated_duration_seconds}s est.</Badge></div>
                      <p className="whitespace-pre-wrap text-fg-muted">{s.spoken_text}</p>
                    </li>
                  ))}
                </ol>
              </CardContent>
            </Card>
          )}
        </div>
      )}
    </>
  );
}
