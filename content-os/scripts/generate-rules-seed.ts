/**
 * Generates supabase/migrations/20261126001100_seed_creative_rules.sql from
 * src/server/creative/rules/library.ts.  Run: npm run rules:seed
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CREATIVE_RULE_LIBRARY } from "../src/server/creative/rules/library";

const q = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (xs: string[], type: string) => (xs.length ? `array[${xs.map(q).join(", ")}]::${type}[]` : `'{}'::${type}[]`);
const num = (n: number | null) => (n === null ? "null" : String(n));

const slugs = new Set<string>();
for (const r of CREATIVE_RULE_LIBRARY) {
  if (slugs.has(r.slug)) throw new Error(`Duplicate slug ${r.slug}`);
  slugs.add(r.slug);
}

const rows = CREATIVE_RULE_LIBRARY.map(
  (r) => `  (${q(r.slug)}, ${q(r.name)}, ${q(r.category)}::public.creative_rule_category, ${q(r.description)}, ${q(r.objective)},
   ${arr(r.application_conditions, "text")}, ${arr(r.avoidance_conditions, "text")}, ${q(r.example)},
   ${arr(r.recommended_formats, "public.script_format")}, ${arr(r.objectives, "text")}, ${arr(r.tones_excluded, "text")},
   ${num(r.min_duration_seconds)}, ${num(r.max_duration_seconds)}, ${q(r.complexity_level)}::public.creative_complexity,
   ${q(r.evidence_type)}::public.creative_evidence_type, ${q(r.evidence_note)}, 'approved'::public.creative_rule_status, now())`,
);

const tags = CREATIVE_RULE_LIBRARY.flatMap((r) => r.tags.map((t) => `  (${q(r.slug)}, ${q(t)})`));

const sql = `-- =============================================================================
-- Content OS — Phase 3 — Migration 1100: initial creative rule library
-- GENERATED by scripts/generate-rules-seed.ts from
-- src/server/creative/rules/library.ts — do not edit by hand.
-- ${CREATIVE_RULE_LIBRARY.length} global rules (workspace_id IS NULL), status approved.
-- =============================================================================

insert into public.creative_rules (slug, name, category, description, objective, application_conditions, avoidance_conditions,
  example, recommended_formats, objectives, tones_excluded, min_duration_seconds, max_duration_seconds, complexity_level,
  evidence_type, evidence_note, status, approved_at)
values
${rows.join(",\n")}
on conflict (slug) where workspace_id is null do nothing;

insert into public.creative_rule_tags (rule_id, tag)
select r.id, t.tag
from (values
${tags.join(",\n")}
) as t(slug, tag)
join public.creative_rules r on r.slug = t.slug and r.workspace_id is null
on conflict do nothing;
`;

const out = fileURLToPath(new URL("../supabase/migrations/20261126001100_seed_creative_rules.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${CREATIVE_RULE_LIBRARY.length} rules and ${tags.length} tags to ${out}`);
